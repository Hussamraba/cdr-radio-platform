#!/usr/bin/env bash
set +x
set -euo pipefail
umask 077

if [[ ! -t 0 ]]; then
  printf 'Run this command in an interactive Ubuntu terminal.\n' >&2
  exit 2
fi

cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.."
if [[ -e backend/.env || -L backend/.env ]]; then
  printf 'backend/.env already exists. It was left in place.\n' >&2
  exit 2
fi
if [[ ! -r backend/dist/password.js || ! -r backend/dist/config.js ]]; then
  printf 'Build the backend with npm run build --prefix backend first.\n' >&2
  exit 2
fi

unset cdr_operator_key cdr_operator_password cdr_operator_confirm cdr_operator_hash
read -rsp 'Dedicated AzuraCast API key: ' cdr_operator_key
printf '\n'
if [[ ! "$cdr_operator_key" =~ ^[0-9a-f]{16}:[0-9a-f]{32}$ ]]; then
  printf 'Copy the complete key generated by AzuraCast 0.24.1.\n' >&2
  exit 2
fi
read -rsp 'Independent private app password (12+ bytes): ' cdr_operator_password
printf '\n'
read -rsp 'Repeat the private app password: ' cdr_operator_confirm
printf '\n'
if [[ "$cdr_operator_password" != "$cdr_operator_confirm" ]]; then
  printf 'The passwords did not match.\n' >&2
  exit 2
fi
cdr_operator_hash=$(printf '%s' "$cdr_operator_password" | env -i PATH="$PATH" node backend/dist/password.js)
unset cdr_operator_password cdr_operator_confirm

temporary=$(mktemp backend/.env.setup.XXXXXX)
trap 'rm -f -- "$temporary"' EXIT
{
  sed -E '/^(AZURACAST_API_KEY|ADMIN_PASSWORD_HASH)=/d' backend/.env.example
  printf 'AZURACAST_API_KEY=%s\nADMIN_PASSWORD_HASH=%s\n' "$cdr_operator_key" "$cdr_operator_hash"
} > "$temporary"
unset cdr_operator_key cdr_operator_hash

env -i PATH="$PATH" node --env-file="$temporary" --input-type=module -e '
  import { loadConfig } from "./backend/dist/config.js";
  try {
    const config = loadConfig(process.env);
    if (config.allowWrites || config.origin.origin !== "http://127.0.0.1:18090" ||
        process.env.ADMIN_LISTEN_PORT !== "18090" || config.azuraOrigin.origin !== "http://127.0.0.1") {
      throw new Error();
    }
  } catch {
    console.error("The operator configuration failed validation.");
    process.exitCode = 1;
  }
'
ln --no-target-directory -- "$temporary" backend/.env
printf 'Created backend/.env with mode 600. Music writes are disabled.\n'
